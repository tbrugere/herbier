(* Herbier_ui_model.Wgsrpd_fr: the generated WGSRPD code -> French name table.
   Generated by scripts/wgsrpd-fr.py from Wikidata's French P11897 labels plus
   scripts/wgsrpd-fr-overrides.tsv; read, never written, by this suite. The
   table is generated outside the suite, so a few entries are pinned by name,
   and every override of the TSV is checked against it. *)

module Wgsrpd_fr = Herbier_ui_model.Wgsrpd_fr
module Fixture = Herbier_test_support.Fixture

let generated_on_is_the_snapshot_date () =
  Alcotest.(check string) "generated_on" "2026-11-21" Wgsrpd_fr.generated_on

let known_codes () =
  let case expected code =
    Alcotest.(check (option string))
      (Printf.sprintf "name %S" code)
      expected (Wgsrpd_fr.name code)
  in
  case (Some "Belgique") "BGM";
  case (Some "Corse") "COR";
  case (Some "France") "FRA";
  case (Some "Allemagne") "GER";
  case (Some "Îles Canaries") "CNY"

let override_is_non_empty_and_not_the_english_name () =
  match Wgsrpd_fr.name "AGE" with
  | Some s ->
      Alcotest.(check bool) "non-empty" true (String.length s > 0);
      Alcotest.(check bool)
        "not GBIF's English locality" true
        (not (String.equal s "Argentina Northeast"))
  | None -> Alcotest.fail "AGE: expected a hand-translated override, got None"

let unknown_or_malformed_codes_give_none () =
  let case what code =
    Alcotest.(check bool)
      (what ^ ": None") true
      (Option.is_none (Wgsrpd_fr.name code))
  in
  case "the empty string" "";
  case "a known code in the wrong case" "bgm";
  case "a code absent from WGSRPD" "ZZZ"

(* Every WCVP level-3 code of the recorded distributions has a French name;
   other sources' TDWG: rows are excluded, as in Projection.project. *)
let wcvp_source = "The World Checklist of Vascular Plants (WCVP)"
let tdwg_prefix = "TDWG:"

let tdwg_codes_of_fixture name : string list =
  match Yojson.Safe.from_string (Fixture.read name) with
  | `Assoc fields -> (
      match List.assoc_opt "results" fields with
      | Some (`List results) ->
          List.filter_map
            (function
              | `Assoc kvs
                when match List.assoc_opt "source" kvs with
                     | Some (`String s) -> String.equal s wcvp_source
                     | _ -> false -> (
                  match List.assoc_opt "locationId" kvs with
                  | Some (`String s)
                    when String.length s > String.length tdwg_prefix
                         && String.equal
                              (String.sub s 0 (String.length tdwg_prefix))
                              tdwg_prefix ->
                      Some
                        (String.sub s
                           (String.length tdwg_prefix)
                           (String.length s - String.length tdwg_prefix))
                  | _ -> None)
              | _ -> None)
            results
      | _ -> Alcotest.failf "%s: no results member" name)
  | _ -> Alcotest.failf "%s: not a JSON object" name

let every_fixture_wcvp_code_has_a_french_name () =
  let codes =
    List.sort_uniq String.compare
      (tdwg_codes_of_fixture "gbif_distributions_5414995.json"
      @ tdwg_codes_of_fixture "gbif_distributions_5405976.json")
  in
  Alcotest.(check bool) "at least one code found" true (codes <> []);
  List.iter
    (fun code ->
      Alcotest.(check bool)
        (Printf.sprintf "%s has a French name" code)
        true
        (Option.is_some (Wgsrpd_fr.name code)))
    codes

(* The generator lets the TSV win over Wikidata, so the table must hold every
   override: an edit of the TSV without a new run of the script fails here. *)
let overrides = "../../scripts/wgsrpd-fr-overrides.tsv"

let every_override_is_in_the_table () =
  let rows =
    In_channel.with_open_bin overrides In_channel.input_lines
    |> List.filter (fun line ->
        not (String.equal line "" || String.starts_with ~prefix:"#" line))
  in
  Alcotest.(check bool) "the TSV has overrides" true (rows <> []);
  List.iter
    (fun line ->
      match String.split_on_char '\t' line with
      | [code; name] ->
          Alcotest.(check (option string))
            code (Some name) (Wgsrpd_fr.name code)
      | _ -> Alcotest.failf "%s: not code<TAB>name: %S" overrides line)
    rows

let case name f = Alcotest.test_case name `Quick f

let wgsrpd_fr =
  [
    case "generated_on is the 2026-11-21 snapshot date"
      generated_on_is_the_snapshot_date;
    case "known WGSRPD codes: BGM, COR, FRA, GER, CNY (capitalised)" known_codes;
    case
      "AGE (a hand-translated override) is non-empty and not the English \
       locality name"
      override_is_non_empty_and_not_the_english_name;
    case "\"\", a lowercase code, an unknown code: None"
      unknown_or_malformed_codes_give_none;
    case
      "every level-3 WCVP code of the two spike species' fixtures has a French \
       name (the overrides cover them)"
      every_fixture_wcvp_code_has_a_french_name;
    case "every override of scripts/wgsrpd-fr-overrides.tsv is in the table"
      every_override_is_in_the_table;
  ]
