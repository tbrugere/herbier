"""Writes app/ui_model/wgsrpd_fr.ml: the French names of the WGSRPD areas
(TDWG's World Geographical Scheme for Recording Plant Distributions), the codes
of GBIF's WCVP distribution rows (`TDWG:BGM`).

Source: Wikidata's French labels of the items with P11897 (WGSRPD ID, CC0),
first letter capitalised; scripts/wgsrpd-fr-overrides.tsv wins over them and
covers the level-3 areas Wikidata does not label. Every level-3 code of TDWG's
list must end up with a name (exit 1 otherwise, unless --allow-missing).

    uv run scripts/wgsrpd-fr.py [--out PATH] [--allow-missing]

Then run `dune build @app/fmt --auto-promote`. There is no --check: Wikidata
changes, so the table is a snapshot dated in its header.
"""

import argparse
import csv
import datetime
import json
import sys
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OVERRIDES = ROOT / "scripts" / "wgsrpd-fr-overrides.tsv"
DEFAULT_OUT = ROOT / "app" / "ui_model" / "wgsrpd_fr.ml"
USER_AGENT = "Herbier/0 scripts (https://github.com/tbrugere/herbier)"
SPARQL = "https://query.wikidata.org/sparql"
QUERY = """SELECT ?item ?code ?fr WHERE {
  ?item wdt:P11897 ?code .
  OPTIONAL { ?item rdfs:label ?fr FILTER(LANG(?fr) = "fr") }
}"""
LEVEL3 = (
    # Pinned: the last commit of tdwg/wgsrpd (2021), so a run reads the list
    # the committed table was checked against.
    "https://raw.githubusercontent.com/tdwg/wgsrpd/"
    "52da7828aba9d461dd133c27b3bd7a4407161f54/"
    "109-488-1-ED/2nd%20Edition/tblLevel3.txt"
)


def fetch(url: str, accept: str) -> bytes:
    request = urllib.request.Request(
        url, headers={"Accept": accept, "User-Agent": USER_AGENT}
    )
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read()


def qid_number(uri: str) -> int:
    _, sep, number = uri.rpartition("/Q")
    if not sep or not number.isdigit():
        sys.exit(f"not a Wikidata item URI: {uri}")
    return int(number)


def wikidata_labels() -> dict[str, str]:
    url = SPARQL + "?" + urllib.parse.urlencode({"query": QUERY})
    body = json.loads(fetch(url, "application/sparql-results+json"))
    best: dict[str, tuple[int, str]] = {}
    for row in body["results"]["bindings"]:
        if "fr" not in row:
            continue
        code = row["code"]["value"]
        label = row["fr"]["value"]
        qid = qid_number(row["item"]["value"])
        if code not in best or qid < best[code][0]:
            best[code] = (qid, label)
    return {code: label[:1].upper() + label[1:] for code, (_, label) in best.items()}


def overrides() -> dict[str, str]:
    names = {}
    with OVERRIDES.open(encoding="utf-8", newline="") as f:
        for n, row in enumerate(csv.reader(f, delimiter="\t"), start=1):
            if not row or row[0].startswith("#"):
                continue
            if len(row) < 2:
                sys.exit(f"{OVERRIDES}:{n}: expected code<TAB>name")
            code, name = row[0].strip(), row[1].strip()
            names[code] = name
    return names


def level3_codes() -> list[tuple[str, str]]:
    text = fetch(LEVEL3, "text/plain").decode("latin-1")
    lines = text.splitlines()
    rows = []
    for line in lines[1:]:
        fields = line.split("*")
        if len(fields) >= 2 and fields[0].strip():
            rows.append((fields[0].strip(), fields[1].strip()))
    return rows


def ocaml_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write(out: Path, names: dict[str, str], day: str) -> None:
    lines = [
        f"(* Generated by scripts/wgsrpd-fr.py on {day}; do not edit. *)",
        "",
        f"let generated_on = {ocaml_string(day)}",
        "",
        "let name = function",
    ]
    for code in sorted(names):
        lines.append(f"  | {ocaml_string(code)} -> Some {ocaml_string(names[code])}")
    lines.append("  | _ -> None")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--allow-missing", action="store_true")
    args = parser.parse_args()

    names = wikidata_labels()
    names.update(overrides())
    missing = [(c, n) for c, n in level3_codes() if c not in names]
    for code, english in missing:
        print(f"no French name: {code}\t{english}", file=sys.stderr)
    if missing and not args.allow_missing:
        return 1
    write(args.out, names, datetime.date.today().isoformat())
    return 0


if __name__ == "__main__":
    sys.exit(main())
